// Генератор Ёлки XL (32×32) в hex-формате.
// Используемые цвета:
//   1=контур(чёрный) 3=хвоя(тёмно-зелёный) 6=ствол(коричневый)
//   8=красный шар 9=жёлтый шар 10=синий шар 12=золотая звезда
//   11=снег(белый) 14=оранжевый шар 15=фон(тёмно-синий)
//   2,4,5,7,13 — резерв палитры (не используются)
function generateFirTree() {
  const size = 32;
  const grid = [];
  for (let y = 0; y < size; y++) grid.push(new Array(size).fill(15));

  const cx = Math.floor(size / 2);
  const top = Math.floor(size * 0.15);
  const bot = Math.floor(size * 0.85);
  const maxW = Math.floor(size * 0.75);

  function drawTri(y1, y2, w1, w2) {
    for (let y = y1; y <= y2; y++) {
      const t = (y - y1) / Math.max(1, y2 - y1);
      const w = Math.floor(w1 + (w2 - w1) * t);
      const halfW = Math.floor(w / 2);
      const l = cx - halfW, r = cx + halfW;
      for (let x = l; x <= r; x++) {
        if (x < 0 || x >= size) continue;
        grid[y][x] = (x === l || x === r) ? 1 : 3;
      }
    }
  }

  drawTri(top, top + 6, 3, 11);
  drawTri(top + 6, top + 12, 5, 17);
  drawTri(top + 12, bot, 7, maxW);

  const tTop = bot, tBot = size - 3, tHW = 2;
  for (let y = tTop; y <= tBot; y++) {
    for (let x = cx - tHW; x <= cx + tHW; x++) {
      if (x < 0 || x >= size) continue;
      grid[y][x] = (x === cx - tHW || x === cx + tHW) ? 1 : 6;
    }
  }

  const sY = top - 4;
  for (let dy = 0; dy < 4; dy++) {
    const y = sY + dy;
    if (y < 0 || y >= size) continue;
    const halfW = Math.min(dy, 2);
    for (let dx = -halfW; dx <= halfW; dx++) {
      const x = cx + dx;
      if (x >= 0 && x < size && grid[y][x] === 15) grid[y][x] = 12;
    }
  }

  const toys = [
    { y: top + 7,  x: cx - 5,  c: 8  }, { y: top + 7,  x: cx + 5,  c: 9  },
    { y: top + 10, x: cx - 7,  c: 10 }, { y: top + 10, x: cx + 7,  c: 8  },
    { y: top + 13, x: cx - 3,  c: 9  }, { y: top + 13, x: cx + 3,  c: 10 },
    { y: top + 16, x: cx - 9,  c: 8  }, { y: top + 16, x: cx + 9,  c: 14 },
    { y: top + 19, x: cx - 5,  c: 10 }, { y: top + 19, x: cx + 5,  c: 8  },
    { y: top + 22, x: cx - 11, c: 9  }, { y: top + 22, x: cx + 11, c: 10 }
  ];
  for (const t of toys) {
    if (t.y >= 0 && t.y < size && t.x >= 0 && t.x < size && grid[t.y][t.x] === 3) {
      grid[t.y][t.x] = t.c;
    }
  }

  for (let y = size - 3; y < size; y++) {
    for (let x = 0; x < size; x++) {
      if (grid[y][x] === 15) grid[y][x] = 11;
    }
  }

  return grid.map(function (row) {
    return row.map(function (n) { return n.toString(16).padStart(2, '0'); }).join('');
  });
}

